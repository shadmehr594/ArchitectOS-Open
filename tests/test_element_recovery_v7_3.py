def test_the_loss_table_classifies_every_generated_claim():
    record = _live()
    result = record["normalizer_result"]
    raw = json.loads(result["raw_text"])

    categories = ("observed_elements", "walls", "fixtures", "structural_elements",
                  "interpretations", "unknowns")
    generated = sum(len(raw.get(c) or []) for c in categories)
    generated += sum(len(v or []) for v in (raw.get("openings") or {}).values())

    assert generated == 38
    assert result["accepted_claim_count"] == 30
    assert result["rejected_claim_count"] == 8

    # EVERY rejection is a summary-text mismatch, never an invalid quote.
    for failure in result["source_resolution_failures"]:
        assert failure["field"] == "text"
        assert failure["reason"] == "no_match"


def test_the_raw_generated_output_is_unchanged():
    """The model's own output is preserved byte-for-byte, never rewritten."""

    record = _live()
    raw_text = record["normalizer_result"]["raw_text"]

    assert hashlib.sha256(raw_text.encode("utf-8")).hexdigest() == \
        "9a9bc32be350caf42cc5f59d54005dc3c735a45e7da2fff691c19a0242848990"
    assert json.loads(raw_text)  # still parseable, still the model's own output
    assert record["inference_budget"]["text_normalizer_calls_used"] == 1


