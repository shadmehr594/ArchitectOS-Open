"""SOURCE_ANCHORED_ELEMENT_RECOVERY_V7_3 — recovery of stage-C claims.

THE CORRECTION THIS FILE PINS
=============================

V7.2 concluded that the live normalizer "missed planters, the balustrade and the
lanterns". That conclusion was **wrong**. Re-reading the saved raw generated JSON
(`normalizer_result.raw_text`, 38 claims) shows the model DID generate all of
them. All 8 normalizer rejections carry `field="text"`, `reason="no_match"` —
the **source_quote resolved fine**; only the concise summary label was not a
verbatim substring of the descriptive sentence:

    text="lanterns"  quote="Small black metal lantern fixtures with a glowing
                            (lit) glass body, mounted on the wall."

That is a REPRESENTATION loss, not a discovery loss. This file pins the narrow,
strict recovery for exactly that case. V7.4 intentionally extends the accepted
set with bounded appearance evidence while retaining the V7.3 source, negation,
count and duplicate safeguards below.

STAGE LEGEND (Task A)
    A  element never generated by the LLM
    B  generated but source_quote invalid
    C  generated, valid quote, non-verbatim summary text   <-- recoverable set
    D  accepted by the normalizer but rejected by the adapter
    E  accepted and transported

CPU only. Reads saved evidence; no model call is possible in this file.
"""

import hashlib
import json
from pathlib import Path

import pytest

from core.vision.architectural_observation_v1 import (
    build_architectural_observation,
    element_evidence_from_claims,
    recovered_claims_from_failures,
)

ROOT = Path(__file__).resolve().parents[1]
V7_2 = ROOT / "runs" / "architectural_live_element_normalization_v7_2"
LIVE = V7_2 / "20_live_normalization.json"
V7_TEXT = ROOT / "runs" / "architectural_element_vision_v7" / "21_raw_observation.txt"

CROP_SHA = "d981742208b65d27b6243db4780d59a0b901b5c195f4d153e916555141ed866b"
SOURCE_IMAGE = {
    "sha256": CROP_SHA, "width": 890, "height": 510,
    "crop_box": {"left": 440, "top": 790, "right": 1330, "bottom": 1300},
    "parent": {"sha256": "1b304a9f2c34819015fbc1b9a15d930f4c2d9fd011572677d648748a15c0231c",
               "width": 2000, "height": 1682},
}

HISTORICAL_V7_3_CARRIED_RECORDS = 20
V7_4_CARRIED_EVIDENCE_RECORDS = 26


def _source_text():
    return V7_TEXT.read_text(encoding="utf-8")


def _live():
    return json.loads(LIVE.read_text(encoding="utf-8"))


def _failures():
    return _live()["normalizer_result"]["source_resolution_failures"]


def _anchor(claims):
    observation = build_architectural_observation(
        {"observed": [], "image_type": "facade"}, image_id="v7-live")
    return element_evidence_from_claims(
        observation, claims, _source_text(), source_image=SOURCE_IMAGE)


