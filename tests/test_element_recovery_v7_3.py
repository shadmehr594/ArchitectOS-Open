def test_a_lantern_claim_rejected_only_for_its_text_is_recovered():
    recovered = recovered_claims_from_failures(_failures(), _source_text())
    lanterns = [c for c in recovered if (c.get("text") or "").lower() == "lanterns"]

    assert lanterns, "the lantern claim was not recovered"

    anchored, report = _anchor(lanterns)
    entry = anchored["element_evidence"]["elements"][0]

    assert entry["evidence_class"] == "MODEL_REPORTED"
    assert "light_fixture" in entry["kind"]
    assert entry["element"] == "lanterns"
    assert entry["source_quote"].startswith("Small black metal lantern fixtures")


def test_a_balustrade_claim_rejected_only_for_its_text_is_recovered():
    recovered = recovered_claims_from_failures(_failures(), _source_text())
    balustrade = [c for c in recovered
                  if (c.get("text") or "").lower() == "balustrade"]

    assert balustrade

    anchored, _ = _anchor(balustrade)
    entry = anchored["element_evidence"]["elements"][0]

    assert entry["kind"] == ["railing"]
    assert entry["declared_kind"] == "balustrade"


def test_a_planter_claim_is_recovered_via_v7_4_appearance_rule():
    """V7.4 — the quote describes a wall-mounted receptacle with plants.

    The appearance rule (receptacle + plant + mounted) supports planter safely.
    """

    recovered = recovered_claims_from_failures(_failures(), _source_text())
    planter = [c for c in recovered if (c.get("text") or "").lower() == "planter"]

    assert len(planter) == 1
    assert planter[0].get("text_is_model_label") is True


def test_a_carved_relief_band_is_recovered_as_decorative_band():
    """V7.4 — the quote describes a horizontal carved band.

    The appearance rule supports a generic decorative_band without asserting a
    specific classical type.
    """

    recovered = recovered_claims_from_failures(_failures(), _source_text())
    band = [c for c in recovered if "carved relief" in (c.get("text") or "").lower()]

