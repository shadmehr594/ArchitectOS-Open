# ==========================================================
# SPATIAL INTENT HANDOFF — T2I_BALCONY_SPATIAL_HANDOFF_V1
#
# The semantic intent describes an object with STRUCTURED spatial claims:
#
#     {"name": "balcony",         "properties": {"location": "upper_floors"}}
#     {"name": "balcony_railing", "properties": {"material": "metal",
#                                                "attached_to": "balcony"}}
#     {"name": "rooftop_parapet", "properties": {"material": "stone",
#                                                "location": "rooftop"}}
#
# This builder kept only identifier/color/name, so both claims were discarded:
# "balcony on an upper floor" collapsed into "balcony placed naturally in
# architectural scene" and the validated floor was lost from the prompt.
#
# Only values from the CLOSED vocabularies below are spoken. An unrecognised or
# missing value yields NO phrase, so an object whose floor the user never
# stated can never be given an invented location, and no phrase is ever added
# for a property the intent does not carry.
#
# The optional third element is the wording the object's OWN NAME already
# implies ("rooftop_parapet" already says rooftop); it is not repeated.
# ==========================================================


_OBJECT_LOCATION_PHRASES = (

    ("ground floor", "on the ground floor", "ground floor"),

    ("upper floor", "on an upper floor", "upper floor"),

    ("rooftop", "on the rooftop", "rooftop"),

    ("roof", "on the rooftop", "roof"),

    ("terrace", "on the terrace", "terrace"),

    ("balcony", "on the balcony", "balcony"),

    ("facade", "on the facade", "facade"),

    ("entrance", "at the entrance", "entrance"),

)


#: Attachment targets that name no architectural element.
_ATTACHMENT_TARGET_STOPWORDS = (

    "it", "itself", "self", "building", "the building", "unknown",

    "none", "null", "n/a",

)


def _normalized_property_text(value):
    """A structured property value as lowercase spaced tokens, or ""."""

    if value is None:

        return ""

    return " ".join(
        str(value).strip().lower().replace("_", " ").split()
    )


def _object_property_source(obj):
    """The mapping that carries an object's structured properties.

    The semantic intent is produced in BOTH shapes — nested properties::

        {"name": "balcony", "properties": {"location": "upper_floors"}}

    and flat::

        {"name": "balcony", "location": "upper_floors"}

    Both are generated by the understanding layer, so both are read here and
    neither is treated as the only valid carrier.
    """

    if not isinstance(obj, dict):

        return {}

    properties = obj.get("properties")

    if isinstance(properties, dict):

        return properties

    return obj


def _object_location_phrase(object_text, value):
    """The validated LOCATION phrase for an object, or "" when not known."""

    key = _normalized_property_text(value)

    if not key:

        return ""

    for trigger, phrase, implied in _OBJECT_LOCATION_PHRASES:

        if trigger not in key:

            continue

        if implied and implied in object_text:

            return ""

        return phrase

    return ""


def _object_attachment_phrase(value):
    """The validated ATTACHMENT phrase for an object, or "" when not known."""

    target = _normalized_property_text(value)

    if not target or len(target) > 40:

        return ""

    if target in _ATTACHMENT_TARGET_STOPWORDS:

        return ""

    if not all(
        character.isalnum() or character in " -"
        for character in target
    ):

        return ""

    return "attached to the " + target


def _object_spatial_phrase(object_text, properties):
    """The spatial phrase the intent itself states, or "".

    Provenance is the object's own `properties` field: nothing is derived from
    the user text, and an unstated floor or attachment stays unstated.
    """

    if not isinstance(properties, dict):

        return ""

    lowered = str(object_text or "").lower()

    location = _object_location_phrase(
        lowered,
        properties.get("location")
    )

    attachment = _object_attachment_phrase(
        properties.get("attached_to")
    )

    return " ".join(
        part for part in (location, attachment) if part
    )


class PromptBuilder:


    VERSION = "2.7"



    def __init__(self):

        print(
            "🚀 PROMPT BUILDER v2.7 ONLINE"
        )



    def clean_list(
        self,
        items
    ):

        result = []

        seen = set()


        if not isinstance(
            items,
            list
        ):

            items = [
                items
            ]



        for item in items:


            value = str(
                item
            ).strip()



            if value and value.lower() not in seen:


                result.append(
                    value
                )


                seen.add(
                    value.lower()
                )



        return result


    def semantic_strings(self, value):
        """Flatten facade knowledge into prompt-safe human-readable terms."""
        result = []
        if isinstance(value, str):
            cleaned = value.replace("_", " ").strip()
            if cleaned:
                result.append(cleaned)
        elif isinstance(value, dict):
            # FINAL_SAMPLER_AUTHORITY_FIX_V1 — ResolvedFacadeKnowledgeV1 is a
            # mixed render/evidence DTO.  Recursively flattening the entire
            # object promoted material-ontology metadata (notably every entry
            # in ``materials.resolved[*].styles``) into design requirements.
            # A request for metal could therefore acquire French Classical,
            # Beaux-Arts, Second Empire, industrial, etc. at the sampler.
            #
            # Project only the DTO's existing render-facing fields.  Explicit
            # user facade details are first so the downstream 24-term budget
            # cannot discard them behind inferred ontology detail.  Material
            # evidence/provenance/compatibility records remain audit metadata;
            # authorized primary/cladding/texture/finish values remain visible.
            if value.get("contract") == "ResolvedFacadeKnowledgeV1":
                projection = [
                    value.get("canonical_style"),
                    value.get("user_facade_details"),
                    value.get("facade_language"),
                    value.get("composition"),
                    value.get("symmetry"),
                    value.get("vertical_horizontal_emphasis"),
                    value.get("solid_void_strategy"),
                    value.get("entrance_hierarchy"),
                    value.get("opening_treatment"),
                    value.get("balcony_treatment"),
                    value.get("parapet_treatment"),
                    value.get("architectural_elements"),
                ]

                materials = value.get("materials")
                if isinstance(materials, dict):
                    projection.extend(
                        materials.get(key)
                        for key in (
                            "primary",
                            "cladding",
                            "texture",
                            "finish",
                        )
                    )

                surface = value.get("surface_strategy")
                if isinstance(surface, dict):
                    projection.extend(
                        surface.get(key)
                        for key in (
                            "cladding",
                            "texture",
                            "finish",
                        )
                    )

                for item in projection:
                    result.extend(self.semantic_strings(item))

                return self.clean_list(result)

            for key, item in value.items():
                if key in (
                    "id",
                    "version",
                    "status",
                    "source",
                    "contract",
                    "provenance",
                    "unresolved",
                    "geometry_preservation_method",
                ):
                    continue
                result.extend(self.semantic_strings(item))
        elif isinstance(value, (list, tuple)):
            for item in value:
                result.extend(self.semantic_strings(item))
        return self.clean_list(result)



    def build(
        self,
        design
    ):



        if not isinstance(
            design, 
            dict
        ):

            design = {}


        if "architectural_intent" not in design:

            design = {
                "architectural_intent": design
            }


        print(
            "🔥 PROMPT BUILDER INPUT:",
            design
        )


        print(
            "DEBUG DESIGN OBJECT:",
            design
        )



        # ======================================================
        # INTENT INPUT COMPATIBILITY
        # Supports:
        #
        # 1) {
        #       "architectural_intent": {...}
        #    }
        #
        # 2) {
        #       "building_type": "...",
        #       "style": "...",
        #       ...
        #    }
        #
        # ======================================================

        if isinstance(
            design,
            dict
        ) and isinstance(
            design.get(
                "architectural_intent"
            ),
            dict
        ):

            intent = design.get(
                "architectural_intent"
            )

        else:

            intent = design



        if not isinstance(
            intent,
            dict
        ):

            intent = {}



        architectural_intent = dict(
            intent
        )



        print(
            "🚨 BUILDER INTENT:",
            architectural_intent
        )

        # ======================================================
        # SPACE INTELLIGENCE
        # ======================================================

        spaces = architectural_intent.get(
            "spaces",
            []
        )

        if not isinstance(
            spaces,
            list
        ):
            spaces = []


        space_features = []

        for space in spaces:

            if isinstance(
                space,
                str
            ):

                space_features.append(
                    space.replace("_", " ")
                )


        space_description = ""

        if space_features:

            space_description = (
                "functional spaces including "
                +
                ", ".join(
                    space_features
                )
            )



        building = architectural_intent.get(

            "building",

            {}

        )



        if not isinstance(

            building,

            dict

        ):


            building = {}




        building_type = (

            architectural_intent.get(

                "building_type"

            )

            or

            building.get(

                "type"

            )

            or

            "house"

        )



        style = (

            architectural_intent.get(

                "style"

            )

            or

            building.get(

                "style"

            )

            or

            "modern"

        )



        levels = (
            architectural_intent.get(
                "levels",
                []
            )
        )


        floors = None

        if isinstance(
            levels,
            list
        ) and levels:

            floors = len(
                levels
            )

        else:

            floor_candidate = architectural_intent.get(
                "floors"
            )

            if floor_candidate is None:

                floor_contract = architectural_intent.get(
                    "floor_count"
                )

                if (
                    isinstance(floor_contract, dict)
                    and floor_contract.get("contract") == "FloorCountV1"
                    and floor_contract.get("source") == "user_explicit"
                ):

                    floor_candidate = floor_contract.get(
                        "value"
                    )

            if floor_candidate is None:

                floor_candidate = design.get(
                    "floors"
                )

            # FINAL_SAMPLER_AUTHORITY_FIX_V1 — absence is not evidence for a
            # one-floor building.  Accept only a positive integral value that
            # is actually carried by the existing intent/design contract.
            # Invalid, fractional, zero and negative values remain unspecified
            # instead of being converted into a competing hard claim.
            if not isinstance(floor_candidate, bool):

                try:

                    parsed_floors = int(floor_candidate)

                    if float(floor_candidate) == parsed_floors and parsed_floors > 0:

                        floors = parsed_floors

                except (TypeError, ValueError, OverflowError):

                    floors = None



        if floors == 1:


            floor_text = (

                "single floor building"

            )


        elif floors is not None:


            floor_text = (

                f"{floors} story building"

            )


        else:


            floor_text = ""



        materials = self.clean_list(

            architectural_intent.get(

                "materials",

                []

            )

        )



        # FIX:
        # Keep semantic objects untouched.
        # Do not convert dict objects into strings here.

        objects = architectural_intent.get(

            "objects",

            []

        )


        if not isinstance(

            objects,

            list

        ):


            objects = []



        environment = self.clean_list(

            architectural_intent.get(

                "environment",

                []

            )

        )



        features = []

        facade_terms = []
        for facade_key in (
            "style_analysis",
            "facade_language",
            "climate_facade_strategy",
            "facade_assembly",
            "facade_composition",
            "facade_geometry",
            "material_strategy",
            "resolved_facade_knowledge",
        ):
            facade_terms.extend(
                self.semantic_strings(architectural_intent.get(facade_key))
            )
        if facade_terms:
            # STYLE_FACADE_ELEMENTS_V1 — "UNKNOWN" is a CONTRACT SENTINEL, not a
            # design word. The resolver records a genuine gap structurally in
            # `unresolved`; speaking the sentinel to the image model only
            # pollutes the prompt, so it is dropped here and nowhere else.
            facade_terms = [
                term
                for term in facade_terms
                if str(term).strip().upper() != "UNKNOWN"
            ]

        if facade_terms:
            features.append(
                "approved facade design: " + ", ".join(self.clean_list(facade_terms)[:24])
            )
        # ======================================================
        # STYLE INTELLIGENCE
        # ======================================================


        style_text = str(
            style
        ).lower()



        if "iran" in style_text:


            features.extend([

                "traditional iranian architecture",

                "persian architectural elements",

                "brick courtyard house",

                "iranian heritage design"

            ])



        elif "traditional" in style_text:


            features.extend([

                "traditional architecture",

                "regional architectural character"

            ])



        elif "modern" in style_text:


            features.append(

                "minimal modern architecture"

            )


            # KNOWLEDGE_RECOVERY_01 — FABRICATED DEFAULTS REMOVED.
            #
            # This branch used to append "glass facade" and "natural
            # stone materials" whenever the user had not named a
            # material. The user never asked for either, so the render
            # prompt asserted materials the request did not contain.
            #
            # No replacement vocabulary is added here: an unspecified
            # material stays unspecified, and any material the request
            # DOES carry already reaches the prompt through `materials`
            # and through the resolved facade knowledge harvested above.




        # ======================================================
        # MATERIAL INTELLIGENCE
        # ======================================================


        for material in materials:


            if material == "brick":


                features.append(

                    "traditional brick facade"

                )


            else:


                features.append(

                    material

                )





        # ======================================================
        # ENVIRONMENT INTELLIGENCE
        # ======================================================


        for env in environment:


            env = env.lower()



            if "river" in env:


                features.extend([

                    "beside a fast flowing river",

                    "natural riverside landscape",

                    "water reflections",

                    "lush river environment"

                ])



            else:


                features.append(

                    env

                )





        # ======================================================
        # CAMERA + LIGHT
        # ======================================================


        features.extend([

            "architectural photography",

            "35mm lens",

            "golden hour natural lighting",

            "cinematic realistic render",

            "physically accurate materials",

            "8k ultra realistic"

        ])





        features = self.clean_list(

            features

        )
        # ======================================================
        # OBJECT INTELLIGENCE
        # ======================================================


        objects = architectural_intent.get(
            "objects",
            []
        )

        if not isinstance(objects, list):
            objects = []




        for obj in objects:


            print(

                "🔥 OBJECT BEFORE PROMPT:",

                obj

            )



            object_text = None




            # ------------------------------------------
            # OBJECT AS DICT
            # ------------------------------------------


            if isinstance(

                obj,

                dict

            ):


                name = obj.get(

                    "name",

                    "modern object"

                )



                properties = obj.get(

                    "properties",

                    {}

                )



                if isinstance(

                    properties,

                    dict

                ):


                    color = properties.get(

                        "color",

                        ""

                    )


                    model = properties.get(

                        "model",

                        ""

                    )


                    make = properties.get(

                        "make",

                        ""

                    )



                    identifier = (

                        make

                        or

                        model

                    )



                    parts = [

                        identifier,

                        color,

                        name

                    ]



                    object_text = " ".join(

                        str(p)

                        for p in parts

                        if p

                    )


                    # T2I_BALCONY_SPATIAL_HANDOFF_V1 — preserve the
                    # structured location / attached_to claims the intent
                    # already carries, instead of flattening them away.
                    spatial = _object_spatial_phrase(

                        object_text,

                        _object_property_source(obj)

                    )


                    if spatial:

                        print(

                            "🔥 OBJECT SPATIAL PROVENANCE:",

                            object_text,

                            "->",

                            spatial

                        )


                        object_text = object_text + " " + spatial



                else:


                    object_text = str(

                        name

                    )





            # ------------------------------------------
            # OBJECT AS STRING
            # ------------------------------------------


            elif isinstance(

                obj,

                str

            ):


                object_text = obj





            # ------------------------------------------
            # ADD CLEAN OBJECT WITH SEMANTIC MAPPING
            # ------------------------------------------


            if object_text:


                object_lower = object_text.lower()



                if "car" in object_lower:


                    object_text = (

                        f"{object_text} "

                        "parked naturally in front of the building"

                    )


                elif "pool" in object_lower:


                    object_text = (

                        "swimming pool integrated with landscape beside the house"

                    )


                else:


                    object_text = (

                        object_text

                        +

                        " placed naturally in architectural scene"

                    )



                features.append(

                    object_text

                )


                print(

                    "🔥 NORMALIZED OBJECT:",

                    object_text

                )


        print(
            "FEATURE DEBUG RAW:",
            repr(features)
        )


        print(

            "🔥 FINAL FEATURES BEFORE DESCRIPTION:",

            features

        )


        print(
            "🔥 FEATURES RAW REPR:",
            repr(features)
        )   


        # ======================================================
        # FINAL PROMPT
        # ======================================================


        description = (

            f"{style} {building_type} architectural visualization, "

            +

            (f"{floor_text}, " if floor_text else "")

            +

            space_description

            +

            ", "

            +

            ", ".join(

                features

            )

        )



        print(

            "🔥 BUILDER FEATURES:",

            features

        )


        print(

            "🔥 BUILDER OBJECTS RAW:",

            architectural_intent.get(

                "objects"

            )

        )


        print(

            "🔥 BUILDER DESCRIPTION:",

            description

        )


        print(

            "🔥 FINAL BUILT PROMPT:",

            description

        )





        return {


            "type":

                building_type,



            "floors":

                floors,



            "style":

                style,



            "description":

                description


        }



